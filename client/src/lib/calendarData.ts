export function getHwanggeukPosition(hwYear: number, hwMonth: number, hwDay: number): string {
  const dayOfYear = HW_MONTH_DAYS.slice(0, hwMonth - 1).reduce((a, b) => a + b, 0) + hwDay;
  
  if (dayOfYear >= 365) {
    return "尊宮";
  }
  
  const n = dayOfYear - 1;
  const step = Math.floor((n * 2) / 9);
  const cycleIndex = ((step % 81) + 81) % 81;
  
  const first = 2 + Math.floor(cycleIndex / 9);
  const second = 2 + (cycleIndex % 9);
  
  if (first === 10 && second === 10) {
    return "10지10/尊宮";
  }
  
  const isTransitionDay = (n % 9) === 4;
  
  if (isTransitionDay) {
    const nextCycleIndex = ((cycleIndex + 1) % 81);
    const nextFirst = 2 + Math.floor(nextCycleIndex / 9);
    const nextSecond = 2 + (nextCycleIndex % 9);
    return `${first}지${second}/${nextFirst}지${nextSecond}`;
  }
  
  return `${first}지${second}`;
}

export function getJeolguk(hwYear: number, hwMonth: number, hwDay: number): {
  name: string;
  periodType: string;
  sogung: number;
  daegung: number;
} {
  const JEOLGUK_START_YEAR = 2025;
  
  const daysFromHwEpoch = (hwYear - HW_EPOCH_YEAR) * HW_DAYS_PER_YEAR + 
    HW_MONTH_DAYS.slice(0, hwMonth - 1).reduce((a, b) => a + b, 0) + hwDay - 1;
  const sogung = (((daysFromHwEpoch % 9) + 9) % 9) + 1;
  const daegung = ((Math.floor(Math.abs(daysFromHwEpoch) / 9) % 9)) + 1;
  
  if (hwYear < JEOLGUK_START_YEAR) {
    const normalizedDays = ((daysFromHwEpoch % 24) + 24) % 24;
    const name = JEOLGUK_NAMES[normalizedDays] + "절국";
    return { name, periodType: "", sogung, daegung };
  }
  
  const periodInMonth = hwDay >= 18 ? 1 : (hwDay >= 3 ? 0 : -1);
  
  let periodIndex: number;
  if (periodInMonth === -1) {
    if (hwMonth === 1) {
      periodIndex = 23;
    } else {
      periodIndex = (hwMonth - 2) * 2 + 1;
    }
  } else {
    periodIndex = (hwMonth - 1) * 2 + periodInMonth;
  }
  
  const yearOffset = hwYear - JEOLGUK_START_YEAR;
  const totalPeriods = yearOffset * 24 + periodIndex;
  
  const jeolgukIndex = ((totalPeriods % 24) + 24) % 24;
  const name = JEOLGUK_NAMES[jeolgukIndex] + "절국";
  
  return { name, periodType: "", sogung, daegung };
}

const TIME_DIV_HHMM: [number, number][] = [
  [0, 20],
  [21, 140],
  [141, 300],
  [301, 420],
  [421, 540],
  [541, 700],
  [701, 820],
  [821, 940],
  [941, 1100],
  [1101, 1220],
  [1221, 1340],
  [1341, 1500],
  [1501, 1620],
  [1621, 1740],
  [1741, 1900],
  [1901, 2020],
  [2021, 2140],
  [2141, 2300]
];

function calculateSogung(slotIndex: number, daysFromEpoch: number): number {
  const groupIndex = Math.floor(slotIndex / 3);
  const positionInGroup = slotIndex % 3;
  
  const sogungOffset = 8;
  const baseSogung = ((daysFromEpoch + sogungOffset) % 9 + 9) % 9;
  
  const groupStart = (baseSogung + groupIndex) % 9;
  const sogungValue = (groupStart - positionInGroup * 3 + 27) % 9;
  
  return sogungValue + 2;
}

export function getSogungDaegung(date: Date): {
  sogung: number;
  daegung: number;
  timeSlot: number;
  isAM: boolean;
  remainingMinutes: number;
} {
  const hours = date.getHours();
  const minutes = date.getMinutes();
  const timeHHMM = hours * 100 + minutes;
  
  let timeSlot = 0;
  
  if (timeHHMM > 2300) {
    timeSlot = 1;
  } else {
    for (let t = 0; t < TIME_DIV_HHMM.length; t++) {
      if (timeHHMM >= TIME_DIV_HHMM[t][0] && timeHHMM <= TIME_DIV_HHMM[t][1]) {
        timeSlot = t + 1;
        break;
      }
    }
    if (timeSlot === 0) {
      for (let t = TIME_DIV_HHMM.length - 1; t >= 0; t--) {
        if (timeHHMM > TIME_DIV_HHMM[t][1]) {
          timeSlot = t + 2;
          break;
        }
      }
    }
  }
  
  if (timeSlot > 18) timeSlot = 18;
  if (timeSlot < 1) timeSlot = 1;
  
  const isAM = timeSlot <= 9;
  
  let adjustedDate = new Date(date);
  if (hours >= 23) {
    adjustedDate.setDate(adjustedDate.getDate() + 1);
  }
  
  const hwDate = getHwanggeukDate(adjustedDate.getFullYear(), adjustedDate.getMonth() + 1, adjustedDate.getDate());
  const daysFromEpoch = (hwDate.year - HW_EPOCH_YEAR) * HW_DAYS_PER_YEAR + 
    HW_MONTH_DAYS.slice(0, hwDate.month - 1).reduce((a, b) => a + b, 0) + hwDate.day - 1;
  
  const slotIndex = isAM ? (timeSlot - 1) : (timeSlot - 10);
  const sogung = calculateSogung(slotIndex, daysFromEpoch);
  
  const daegungBase = daysFromEpoch * 2 + (isAM ? 1 : 5);
  const daegungIndex = ((daegungBase) % 9 + 9) % 9;
  const daegung = daegungIndex + 2;
  
  const currentSlotIdx = Math.max(0, timeSlot - 1);
  const slotEndHHMM = TIME_DIV_HHMM[Math.min(currentSlotIdx, 17)][1];
  const slotEndMinutes = Math.floor(slotEndHHMM / 100) * 60 + (slotEndHHMM % 100);
  const currentMinutes = hours * 60 + minutes;
  const remainingMinutes = Math.max(0, slotEndMinutes - currentMinutes);
  
  return { sogung, daegung, timeSlot, isAM, remainingMinutes };
}

